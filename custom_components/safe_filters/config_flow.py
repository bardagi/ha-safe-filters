async def _weights_schema(handler: SchemaCommonFlowHandler) -> vol.Schema:
    entity_ids: list[str] = handler.options.get(CONF_ENTITY_IDS, [])
    return vol.Schema(
        {
            vol.Required(CONF_WEIGHTS): section(
                vol.Schema(
                    {
                        vol.Required(entity_id, default=DEFAULT_WEIGHT): _number(
                            min_value=0, max_value=1000
                        )
                        for entity_id in entity_ids
                    }
                ),
                {"collapsed": False},
            ),
            vol.Required(CONF_MIN_WEIGHT, default=DEFAULT_MIN_WEIGHT): _number(
                min_value=0, max_value=100, step=1, unit=PERCENTAGE
            ),
            vol.Required(CONF_OFFSET_LEARNING, default=DEFAULT_OFFSET_LEARNING): _number(
                min_value=0, max_value=10080, step=1, unit=UNIT_MINUTES
            ),
        }
    )


async def _weights_placeholders(handler: SchemaCommonFlowHandler) -> dict[str, str]:
    hass = handler.parent_handler.hass
    lines = []
    for entity_id in handler.options.get(CONF_ENTITY_IDS, []):
        state = hass.states.get(entity_id)
        name = state.attributes.get(ATTR_FRIENDLY_NAME, entity_id) if state else entity_id
        lines.append(f"- `{entity_id}`: {name}")
    return {"sources": "\n".join(lines)}


async def _unit_placeholders(handler: SchemaCommonFlowHandler) -> dict[str, str]:
    measurement = handler.options.get(CONF_MEASUREMENT)
    return {"unit": (measurement["unit"] or "-") if valid_measurement(measurement) else "-"}


@functools.cache
def _chart_placeholders() -> dict[str, str]:
    """Data URIs of the filter charts, used as images in the filter descriptions."""
    return {
        f"{key}_chart": "data:image/svg+xml;base64,"
        + base64.b64encode((CHART_DIR / f"{key}.svg").read_bytes()).decode("ascii")
        for key in CHART_SECTIONS
    }


async def _filters_placeholders(handler: SchemaCommonFlowHandler) -> dict[str, str]:
    charts = await handler.parent_handler.hass.async_add_executor_job(_chart_placeholders)
    return {**await _unit_placeholders(handler), **charts}


async def _validate_sources(
    handler: SchemaCommonFlowHandler, user_input: dict[str, Any]
) -> dict[str, Any]:
    entity_ids = source_ids(user_input)
    if not entity_ids:
        raise SchemaFlowError("no_sources")
    if len(set(entity_ids)) != len(entity_ids):
        raise SchemaFlowError("duplicate_sources")
    hass = handler.parent_handler.hass
    entry = getattr(handler.parent_handler, "config_entry", None)
    if has_dependency_cycle(hass, None if entry is None else entry.entry_id, entity_ids):
        raise SchemaFlowError("dependency_cycle")
    states = [hass.states.get(entity_id) for entity_id in entity_ids]
    saved = handler.options.get(CONF_MEASUREMENT)
    inferred = measurement_from_states(states)
    baseline = saved if valid_measurement(saved) else inferred
    advanced = user_input.get(CONF_ADVANCED) or {}
    unit = advanced.get("unit", "").strip() or (baseline["unit"] if baseline else None)
    selected_class = advanced.get("device_class")
    if selected_class == NO_DEVICE_CLASS:
        device_class = None
    elif selected_class == AUTO_DEVICE_CLASS:
        automatic = inferred or baseline
        if automatic is None:
            raise SchemaFlowError("source_metadata_unknown")
        device_class = automatic["device_class"]
    elif selected_class is not None:
        device_class = numeric_device_class(selected_class)
        if device_class is None:
            raise SchemaFlowError("invalid_device_class")
    else:
        device_class = baseline["device_class"] if baseline else None
    if baseline is None and not unit and selected_class in (None, AUTO_DEVICE_CLASS):
        raise SchemaFlowError("source_metadata_unknown")
    measurement = {"unit": unit, "device_class": device_class}
    if not measurement_supported(measurement):
        raise SchemaFlowError("invalid_measurement_unit")
    if not all(matches_measurement(state, measurement) for state in states):
        raise SchemaFlowError(
            "incompatible_measurement" if valid_measurement(saved) else "incompatible_units"
        )
    if valid_measurement(saved) and saved != measurement:
        _change_measurement_settings(handler.options, saved, measurement)
    user_input.pop(CONF_ADVANCED, None)
    user_input[CONF_MEASUREMENT] = dict(measurement)
    return user_input


def _change_measurement_settings(
    options: dict[str, Any], old: Mapping[str, Any], new: Mapping[str, Any]
) -> None:
    """Keep thresholds physically equivalent, or clear incompatible settings."""
    converted = deepcopy(options)
    compatible = not (
        old["device_class"] is not None
        and new["device_class"] is not None
        and old["device_class"] != new["device_class"]
    ) and not (old["unit"] != new["unit"] and None in (old["unit"], new["unit"]))

    def change(value: Any, *, delta: bool = False) -> float:
        if not compatible:
            raise ValueError("different measurement")
        device_class = new["device_class"] or old["device_class"]
        result = convert_value(float(value), old["unit"], new["unit"], device_class)
        zero = convert_value(0.0, old["unit"], new["unit"], device_class) if delta else 0.0
        if result is None or zero is None or not math.isfinite(result - zero):
            raise ValueError("threshold cannot be converted")
        return abs(result - zero) if delta else result

    try:
        # Check even when no range has been configured.
        change(0)
        for key in (CONF_MIN_VALUE, CONF_MAX_VALUE, CONF_MAX_DEVIATION):
            if converted.get(key) is not None:
                converted[key] = change(converted[key], delta=key == CONF_MAX_DEVIATION)
        for key, field in ((CONF_OUTLIER, CONF_RADIUS), (CONF_RATE_LIMIT, CONF_MAX_RATE)):
            if field in (converted.get(key) or {}):
                converted[key][field] = change(converted[key][field], delta=True)
    except (ValueError, TypeError, ArithmeticError):
        for key in (CONF_MIN_VALUE, CONF_MAX_VALUE, CONF_MAX_DEVIATION):
            converted.pop(key, None)
        for key, field, default in (
            (CONF_OUTLIER, CONF_RADIUS, DEFAULT_OUTLIER_RADIUS),
            (CONF_RATE_LIMIT, CONF_MAX_RATE, DEFAULT_MAX_RATE),
        ):
            converted[key] = {**(converted.get(key) or {}), CONF_ENABLED: False, field: default}
    options.clear()
    options.update(converted)


async def _validate_numbers(
    handler: SchemaCommonFlowHandler, user_input: dict[str, Any]
) -> dict[str, Any]:
    """Reject non-finite numbers even if a selector accepts them."""

    def check(value: Any) -> None:
        if isinstance(value, Mapping):
            for item in value.values():
                check(item)
        elif isinstance(value, (int, float)) and not math.isfinite(value):
            raise SchemaFlowError("non_finite_number")

    check(user_input)
    return user_input


async def _validate_quality(
    handler: SchemaCommonFlowHandler, user_input: dict[str, Any]
) -> dict[str, Any]:
    await _validate_numbers(handler, user_input)
    min_value = user_input.get(CONF_MIN_VALUE)
    max_value = user_input.get(CONF_MAX_VALUE)
    if min_value is not None and max_value is not None and min_value >= max_value:
        raise SchemaFlowError("min_not_below_max")
    source_count = len(source_ids(handler.options))
    if user_input.get(CONF_MIN_SOURCES, DEFAULT_MIN_SOURCES) > source_count:
        raise SchemaFlowError("min_sources_too_high")
    return user_input


async def _validate_filters(
    handler: SchemaCommonFlowHandler, user_input: dict[str, Any]
) -> dict[str, Any]:
    await _validate_numbers(handler, user_input)
    rate_limit = user_input.get(CONF_RATE_LIMIT) or {}
    if rate_limit.get(CONF_ENABLED) and rate_limit.get(CONF_MAX_RATE, DEFAULT_MAX_RATE) <= 0:
        # A limit of 0 would freeze the value forever.
        raise SchemaFlowError("max_rate_not_positive")
    return user_input


async def _next_after_sources(options: dict[str, Any]) -> str:
    if options.get(CONF_METHOD) == CombineMethod.WEIGHTED_MEAN:
        return "weights"
    return "quality"


async def _choose_source_step(options: dict[str, Any]) -> str:
    """Open the options flow on the source form that matches the entry's kind."""
    return STEP_SINGLE if is_single(options) else STEP_COMBINE


