async def _source_schema(handler: SchemaCommonFlowHandler, *, single: bool) -> vol.Schema:
    """Expose persisted measurement metadata without adding a mandatory step."""
    editing = getattr(handler.parent_handler, "config_entry", None) is not None
    if single:
        base = SINGLE_SOURCE_SCHEMA if editing else SINGLE_USER_SCHEMA
    else:
        base = COMBINE_SOURCES_SCHEMA if editing else COMBINE_USER_SCHEMA
    saved = handler.options.get(CONF_MEASUREMENT)
    known = valid_measurement(saved)
    unit = saved["unit"] if known else ""
    device_class = (saved["device_class"] or NO_DEVICE_CLASS) if known else AUTO_DEVICE_CLASS
    return base.extend(
        {
            vol.Optional(CONF_ADVANCED): section(
                vol.Schema(
                    {
                        vol.Optional("unit", default=unit or ""): selector.TextSelector(),
                        vol.Required("device_class", default=device_class): selector.SelectSelector(
                            selector.SelectSelectorConfig(
                                options=[AUTO_DEVICE_CLASS, NO_DEVICE_CLASS]
                                + [
                                    value.value
                                    for value in SensorDeviceClass
                                    if numeric_device_class(value)
                                ],
                                translation_key="output_device_class",
                                mode=selector.SelectSelectorMode.DROPDOWN,
                            )
                        ),
                        vol.Optional(
                            CONF_READ_ATTRIBUTES, default=_reads_state_attributes(handler.options)
                        ): selector.BooleanSelector(),
                    }
                ),
                {"collapsed": True},
            )
        }
    )


def _reads_state_attributes(options: Mapping[str, Any]) -> bool:
    """Whether a source with a numeric state is set to read one of its attributes."""
    return any(not needs_attribute(entity_id) for entity_id in source_attributes(options))


async def _single_schema(handler: SchemaCommonFlowHandler) -> vol.Schema:
    return await _source_schema(handler, single=True)


async def _combine_schema(handler: SchemaCommonFlowHandler) -> vol.Schema:
    return await _source_schema(handler, single=False)


