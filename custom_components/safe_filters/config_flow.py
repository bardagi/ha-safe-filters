class SafeFiltersConfigFlow(SchemaConfigFlowHandler, domain=DOMAIN):
    """Handle a config or options flow for Safe Filters."""

    VERSION = 1
    # Entry version 1.3 persists measurement identity; legacy entries resolve it
    # from restore data or the complete source metadata during sensor setup.
    MINOR_VERSION = 3

    config_flow = CONFIG_FLOW
    options_flow = OPTIONS_FLOW

    def async_config_entry_title(self, options: Mapping[str, Any]) -> str:
        """Return config entry title."""
        return cast(str, options[CONF_NAME])
