def _source_lines(
    hass: HomeAssistant,
    entity_ids: list[str],
    attributes: Mapping[str, str | None] | None = None,
) -> str:
    """A Markdown list of sources with their names, and the attribute read if any."""
    lines = []
    for entity_id in entity_ids:
        state = hass.states.get(entity_id)
        name = state.attributes.get(ATTR_FRIENDLY_NAME, entity_id) if state else entity_id
        attribute = (attributes or {}).get(entity_id)
        source = f"`{entity_id}` ({attribute})" if attribute else f"`{entity_id}`"
        lines.append(f"- {source}: {name}")
    return "\n".join(lines)


