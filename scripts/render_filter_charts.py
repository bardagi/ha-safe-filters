"""Render the filter charts shown in the Filters step of the config flow and in the README.

Every chart feeds the same noisy example signal through one real filter stage from
custom_components/safe_filters/engine/stages.py, so the pictures follow the code.

Usage: uv run python scripts/render_filter_charts.py
Only files whose content changes are rewritten.
"""

from __future__ import annotations

import pathlib
import random
import sys
from collections.abc import Callable

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from custom_components.safe_filters.engine.stages import (  # noqa: E402
    LowPassStage,
    MovingAverageStage,
    OutlierStage,
    RateLimitStage,
    Stage,
)

CHART_DIR = ROOT / "custom_components" / "safe_filters" / "charts"

# The example: one sample every 30 s for an hour, with noise, three single-sample
# spikes and one real, lasting step.
INTERVAL_S = 30
SAMPLES = 121
BASELINE = 20.0
NOISE = 0.25  # standard deviation
STEP_AT, STEP = 70, 2.5
SPIKES = {18: 3.0, 42: -2.5, 100: 3.5}
SEED = 7

# File stem (= the filter's options key) -> the stage, with settings that show it well.
STAGES: dict[str, Callable[[], Stage]] = {
    "outlier": lambda: OutlierStage(window_size=5, radius=1.0),
    "rate_limit": lambda: RateLimitStage(max_rate_per_min=0.5),
    "lowpass": lambda: LowPassStage(time_constant_s=180),
    "moving_average": lambda: MovingAverageStage(window_s=300),
}

# Shown as <img>, so the theme can't recolor them: each color reads on both the
# light and the dark Home Assistant theme.
WIDTH, HEIGHT, PAD = 320, 100, 6
INPUT_COLOR = "#898781"
OUTPUT_COLOR = "#3987e5"
REJECTED_COLOR = "#e34948"

Point = tuple[float, float]


def example_signal() -> list[Point]:
    """Return (time, value) samples of the example input."""
    rng = random.Random(SEED)
    signal: list[Point] = []
    for index in range(SAMPLES):
        # A sum of three uniforms is close to Gaussian and bit-exact on every platform.
        noise = (rng.random() + rng.random() + rng.random() - 1.5) * 2 * NOISE
        value = BASELINE + noise + (STEP if index >= STEP_AT else 0.0) + SPIKES.get(index, 0.0)
        signal.append((float(index * INTERVAL_S), value))
    return signal


def _points(samples: list[Point], to_xy: Callable[[Point], Point]) -> str:
    return " ".join(f"{x:.1f},{y:.1f}" for x, y in map(to_xy, samples))


def render(key: str, signal: list[Point]) -> str:
    """Return the SVG for one filter applied to ``signal``."""
    values = [value for _, value in signal]
    low, high = min(values), max(values)
    end = signal[-1][0]

    def to_xy(sample: Point) -> Point:
        time, value = sample
        x = PAD + (WIDTH - 2 * PAD) * time / end
        y = HEIGHT - PAD - (HEIGHT - 2 * PAD) * (value - low) / (high - low)
        return x, y

    stage = STAGES[key]()
    output = [(time, stage.process(value, time, new_sample=True)) for time, value in signal]
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}" '
        f'width="{WIDTH}" height="{HEIGHT}">',
        "  <!-- Generated by scripts/render_filter_charts.py; do not edit. -->",
        f'  <polyline fill="none" stroke="{INPUT_COLOR}" stroke-width="1.25" '
        f'stroke-linejoin="round" points="{_points(signal, to_xy)}"/>',
        f'  <polyline fill="none" stroke="{OUTPUT_COLOR}" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round" points="{_points(output, to_xy)}"/>',
    ]
    if isinstance(stage, OutlierStage):
        # Samples the stage ignored: its output differs from its input.
        rings = [
            '    <circle cx="{:.1f}" cy="{:.1f}" r="4"/>'.format(*to_xy(sample))
            for sample, (_, out) in zip(signal, output, strict=True)
            if out != sample[1]
        ]
        group = f'  <g fill="none" stroke="{REJECTED_COLOR}" stroke-width="1.5">'
        lines += [group, *rings, "  </g>"]
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Render all charts; return the number of files changed."""
    CHART_DIR.mkdir(exist_ok=True)
    signal = example_signal()
    changed = 0
    for key in STAGES:
        data = render(key, signal).encode()
        target = CHART_DIR / f"{key}.svg"
        if target.exists() and target.read_bytes() == data:
            continue
        target.write_bytes(data)
        changed += 1
        print(f"updated {target.relative_to(ROOT).as_posix()}")
    return changed


if __name__ == "__main__":
    main()
